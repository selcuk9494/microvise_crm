  static IconData? secondaryOf(IconData icon) {
    final codePoint = _secondary[icon.codePoint];
    return codePoint == null
        ? null
        // Font glyph comes from the verified constant lookup above.
        // ignore: non_const_argument_for_const_parameter
        : IconData(codePoint, fontFamily: _family, fontPackage: _package);
  }
