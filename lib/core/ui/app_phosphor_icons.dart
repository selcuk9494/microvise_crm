class AppPhosphorIcon extends StatelessWidget {
  const AppPhosphorIcon(this.icon, {super.key, this.size, this.color});

  final IconData icon;
  final double? size;
  final Color? color;

  @override
  Widget build(BuildContext context) {
    final secondary = AppPhosphorIcons.secondaryOf(icon);
    if (secondary == null) return Icon(icon, size: size, color: color);
    final resolved = color ?? IconTheme.of(context).color;
    return Stack(
      alignment: Alignment.center,
      children: [
        Icon(secondary, size: size, color: resolved?.withValues(alpha: 0.52)),
        Icon(icon, size: size, color: resolved),
      ],
    );
  }
}
